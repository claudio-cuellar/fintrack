@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly language = signal<Language>(this.readLanguage());
  readonly languages: readonly Language[] = ['en', 'es'];

  setLanguage(language: Language): void {
    this.language.set(language);
    localStorage.setItem('fintrack.language', language);
    this.updateDocumentLanguage(language);
  }

  text(key: string, params: Record<string, string | number> = {}): string {
    const template = translations[this.language()][key] ?? translations.en[key] ?? key;
    return Object.entries(params).reduce((result, [name, value]) => result.replaceAll(`{{${name}}}`, String(value)), template);
  }

  label(language: Language): string {
    return language === 'es' ? this.text('language.spanish') : this.text('language.english');
  }

  private readLanguage(): Language {
    const language = localStorage.getItem('fintrack.language') === 'es' ? 'es' : 'en';
    this.updateDocumentLanguage(language);
    return language;
  }

  private updateDocumentLanguage(language: Language): void {
    if (typeof document !== 'undefined') document.documentElement.lang = language;
  }
}
